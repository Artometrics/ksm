import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let sha = "dev";
try {
  sha = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim();
} catch {
  /* not a git repo in some CI paths */
}
const v = `${sha}-${Date.now()}`;

writeFileSync(join(root, "public", "css-version.txt"), v, "utf8");
mkdirSync(join(root, "constants"), { recursive: true });
writeFileSync(
  join(root, "constants", "CssVersion.ts"),
  `/** Generated by scripts/write-css-version.mjs — do not edit. */\nexport const CSS_VERSION = ${JSON.stringify(v)};\n`,
  "utf8",
);
console.log("[css-version]", v);
